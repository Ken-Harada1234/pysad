def _out(src):
    from pysad.ffscmd import run_sad_string
    buf = io.StringIO()
    run_sad_string(src, out=buf)
    return buf.getvalue()


def _rows(text):
    return [[float(v) for v in l.split()] for l in text.splitlines() if re.match(r'^ +[0-9]+\.[0-9]+ ', l)]


@pytest.mark.parametrize('name', [n for n in NAMES if not n.startswith('cde')])
def test_coord_matches_gs(name):
    ref = globals()[name.upper() + '_REF']
    rows = _rows(_out(globals()[name.upper() + '_SRC']))
    assert len(rows) == len(ref)
    for r, q in zip(rows, ref):
        for a, b in zip(r, q):
            assert abs(a - b) <= 2e-9 * max(abs(b), 1e-3) + 1e-12, (name, r, q)


@pytest.mark.parametrize('name', [n for n in NAMES if n.startswith('cde')])
def test_coord_emittance_matches_gs(name):
    ref = globals()[name.upper() + '_REF']
    got = []
    for l in _out(globals()[name.upper() + '_SRC']).splitlines():
        if l[:4] in ('EMT ', 'TUN ', 'ALP ', 'COD '):
            got.append([float(v) for v in re.findall(r'[-+]?\d*\.?\d+(?:E[-+]?\d+)?', l[4:])])
    assert len(got) == len(ref) == 4
    for r, q in zip(got, ref):
        for a, b in zip(r, q):
            assert abs(a - b) <= 5e-9 * max(abs(b), 1e-3) + 1e-11, (name, r, q)
