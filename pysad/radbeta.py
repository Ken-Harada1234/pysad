@njit(**NJ)
def ab(g):
    """γ = g での (a, b, d ln a/dγ, d ln b/dγ): 光子数に a、光子エネルギーに b を掛ける (a b = β²、a b² = r2/β²)。γ → ∞ で (1, 1, 0, 0)"""
    g = max(g, 1.0005)
    g2 = g * g
    b2 = 1.0 - 1.0 / g2
    beta = math.sqrt(b2)
    dlnb = 1.0 / (g * (g2 - 1.0))                  # d ln β / dγ
    if g <= 30.0:
        lg = math.log(g)
        y = np.interp(lg, _LGRID, _Y)
        k = min(max(int((lg - _LG0) / _DLG), 0), _NT - 2)
        dly = _DY[k] / y / g                         # d ln y / dγ
    else:
        r2 = 1.0 - _CINF / g2 + _DINF / (g2 * g2)
        y = r2 / (b2 * beta)
        dr2 = (2.0 * _CINF / (g2 * g) - 4.0 * _DINF / (g2 * g2 * g)) / r2
        dly = dr2 - 3.0 * dlnb
    a = beta * b2 / y
    b = y / beta
    return a, b, 3.0 * dlnb - dly, dly - dlnb


def r2_of_gamma(g):
    """厳密なスペクトルの 2 次モーメント比 r2(γ) (表)"""
    g = max(g, 1.0005)
    b2 = 1.0 - 1.0 / (g * g)
    if g <= 30.0:
        return float(np.interp(math.log(g), _LGRID, _Y)) * b2 * math.sqrt(b2)
    return 1.0 - _CINF / (g * g) + _DINF / g ** 4


