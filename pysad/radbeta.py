def _intj(nu, x):
    from scipy.integrate import quad
    from scipy.special import jv
    t0 = max(0.0, nu - 14.0 * nu ** (1.0 / 3.0) - 30.0)
    n = max(1, int((x - t0) / 4.0))
    edges = np.linspace(t0, x, n + 1)
    return sum(quad(lambda t: jv(nu, t), edges[i], edges[i + 1], epsabs=1e-15, epsrel=1e-12, limit=100)[0] for i in range(n))


def schott_s(n, beta):
    """S_n (n は実数でもよい)。P_n = (α ħ ω0² / β) n S_n"""
    from scipy.special import jvp
    return 2.0 * beta ** 2 * jvp(2.0 * n, 2.0 * n * beta, 1) - (1.0 - beta ** 2) * _intj(2.0 * n, 2.0 * n * beta)


def r2_exact(g, discrete=None):
    """r2(γ) を Schott の式から直接計算する (離散和 or 連続の n の積分。discrete=None で γ < 2 を離散和)"""
    beta = math.sqrt(1.0 - 1.0 / g ** 2)
    nc = 1.5 * g ** 3
    if discrete is None:
        discrete = g < 2.0
    if discrete:
        ns = np.arange(1, int(40 * nc) + 30 + 1, dtype=float)
        sn = np.array([schott_s(n, beta) for n in ns])
        m2 = float((ns ** 2 * sn).sum())
    else:
        x, w = np.polynomial.legendre.leggauss(140)
        lo, hi = math.log(0.3), math.log(80.0 * nc + 80.0)
        n = np.exp(0.5 * (hi - lo) * x + 0.5 * (hi + lo))
        wn = 0.5 * (hi - lo) * w
        sn = np.array([schott_s(v, beta) for v in n])
        m2 = float((wn * n ** 3 * sn).sum())
    return m2 * beta / (55.0 / (24.0 * math.sqrt(3.0)) * g ** 7)


def build_table(npts=300):
    """表 (_LG0.._LG1 の ln γ の npts 点の r2/β³) を作り直す (数十秒)"""
    lg = np.linspace(_LG0, _LG1, npts)
    ys = []
    for l in lg:
        g = math.exp(l)
        beta = math.sqrt(1.0 - 1.0 / g ** 2)
        ys.append(r2_exact(g) / beta ** 3)
    return lg, np.array(ys)
